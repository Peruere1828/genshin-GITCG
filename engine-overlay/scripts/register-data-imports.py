#!/usr/bin/env python3
"""Regenerate the `@gi-tcg/data` import table (`packages/data/src/index.ts`).

Why this exists
---------------
The engine auto-registers every data file with
`packages/data/scripts/generators/imports.ts` (called only by the destructive
`pnpm regenerate_data`, which also rewrites every character/card `.gts` from raw
data).  We must **not** run that.  Instead, after `apply-overlay.sh` copies our
overlay into `build/engine/`, this script regenerates *only* the `index.ts`
import block, exactly mirroring `imports.ts`:

  * glob `packages/data/src/**/*.{ts,gts}`
  * ignore top-level files (handled by the template: begin/commons/end/index)
  * sort lexicographically
  * emit `import "<relpath>";` lines

It is idempotent: on a tree with no overlay it reproduces upstream `index.ts`
byte-for-byte (verified by `--check`).

Usage:
    register-data-imports.py <engine-root> [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

TARGET_REL = Path("packages/data/src/index.ts")
HEADER_MARK = "// Generated by scripts/generators/imports.ts"


def build_index(engine_root: Path) -> str:
    src = engine_root / "packages" / "data" / "src"
    target = engine_root / TARGET_REL
    existing = target.read_text(encoding="utf-8")

    # Keep the upstream license header untouched (everything up to and including
    # the "Generated by" banner).
    mark_idx = existing.index(HEADER_MARK)
    line_end = existing.index("\n", mark_idx) + 1
    line_end = existing.index("\n", line_end) + 1  # include "// DO NOT EDIT"
    license_header = existing[:line_end]

    files: list[str] = []
    for root, _dirs, names in __import__("os").walk(src):
        for name in names:
            if not (name.endswith(".ts") or name.endswith(".gts")):
                continue
            p = Path(root) / name
            rel = p.relative_to(src)
            if len(rel.parts) == 1:  # top-level: begin/end/index/commons
                continue
            files.append("./" + rel.as_posix())
    files.sort()

    imports = "\n".join(f'import "{f}";' for f in files)
    return (
        f"{license_header}"
        f'\nimport "./begin.ts";\n'
        f'\nimport "./commons.gts";\n'
        f"{imports}\n"
        f'\nexport * from "./end.ts";\n'
        f'export {{ default }} from "./end.ts";\n'
    )


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    engine_root = Path(args[0]).resolve()
    target = engine_root / TARGET_REL
    if not target.is_file():
        print(f"ERR: not a materialized engine tree (missing {target})", file=sys.stderr)
        return 1

    generated = build_index(engine_root)
    current = target.read_text(encoding="utf-8")
    if check:
        if generated == current:
            print(f"[imports] OK: {target} matches generator output")
            return 0
        print(f"[imports] DRIFT: {target} differs from generator output", file=sys.stderr)
        return 1

    if generated != current:
        target.write_text(generated, encoding="utf-8")
        print(f"[imports] regenerated {TARGET_REL}")
    else:
        print(f"[imports] {TARGET_REL} already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
