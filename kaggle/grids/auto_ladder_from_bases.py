"""Turn base certifications into a ladder schedule.

The ladder only pays off on decks whose base already matches the scripted expert
(measured repeatedly: dgeo/unyielding yes, dvalin only from the right base, SA never).
So this script reads the `base_*` certification reports, applies the pre-registered
eligibility rule, and prints the exact `run_single_deck_rl.sh` commands for the
eligible decks -- no hand-picking.

Eligibility (pre-registered):
  * paired delta vs the same deck's scripted expert >= -0.02 (CI_low may dip below
    zero, but the point estimate must not be behind by more than the acceptance slack);
  * absolute pooled rate >= 0.45 (below that the deck is structurally losing and PG
    amplifies noise rather than exploiting).

Usage: python -m kaggle.grids.auto_ladder_from_bases [--emit-script PATH]
"""

from __future__ import annotations

import argparse
import glob
import json
import os

# base checkpoint prefix -> (deck, ladder tag, collect seed start, eval seed start)
PLAN = {
    "gb_mika_bc_d256_e150": ("superconduct_mika_attack", "rl_mika1", 12600, 760),
    "gb_aywolf_bc_d256_e150": ("aywolfskirk", "rl_aywolf1", 12700, 770),
    "gb_natlan_bc_d256_e150": ("natlan_battleship", "rl_natlan1", 12800, 780),
    "gc_klee_bc_d256_e150": ("klee_mavuika_mualani", "rl_klee1", 12000, 790),
    "gc_nahida_bc_d256_e150": ("nahida_kokomi_raiden", "rl_nahida1", 12100, 800),
    "gc_shenhe_bc_d256_e150": ("shenhe_double_swirl", "rl_shenhe1", 12200, 810),
    "gc_electro_bc_d256_e150": ("electro_manifestation_nuke", "rl_electro1", 12300, 820),
    "gc_mualani_bc_d256_e150": ("mualani_double_pyro", "rl_mualani1", 12400, 830),
    "gc_dual_bc_d256_e150": ("dual_mualani_stacks", "rl_dual1", 12500, 840),
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reports", default="reports/explore")
    parser.add_argument("--min-pooled", type=float, default=0.45)
    parser.add_argument("--max-deficit", type=float, default=0.02)
    parser.add_argument("--emit-script", default=None)
    args = parser.parse_args()

    scored: dict[str, tuple[str, float, float, float]] = {}
    for path in glob.glob(os.path.join(args.reports, "base_*.json")):
        if "_2026" in os.path.basename(path):
            continue
        with open(path) as handle:
            data = json.load(handle)
        deck = data["protocol"]["contestant_deck"]
        paired, summary = data["paired_vs_baseline"], data["summary"]
        scored[deck] = (
            data["protocol"]["contestant"].replace("neural:", ""),
            float(paired["delta"]),
            float(paired["ci_low"]),
            float(summary["pooled_rate"]),
        )

    eligible, behind = [], []
    for prefix, (deck, tag, cseed, eseed) in PLAN.items():
        if deck not in scored:
            continue
        ckpt, delta, lo, pooled = scored[deck]
        row = (deck, tag, cseed, eseed, ckpt, delta, lo, pooled)
        (eligible if delta >= -args.max_deficit and pooled >= args.min_pooled else behind).append(row)

    print(f"eligible ({len(eligible)}):")
    for deck, tag, cseed, eseed, ckpt, delta, lo, pooled in sorted(eligible, key=lambda r: -r[5]):
        print(f"  {deck:30s} pooled {pooled:.3f}  Δ {delta:+.3f} [{lo:+.3f},…]  -> {tag}")
    print(f"\nbehind ({len(behind)}) — not laddered:")
    for deck, tag, cseed, eseed, ckpt, delta, lo, pooled in sorted(behind, key=lambda r: -r[5]):
        print(f"  {deck:30s} pooled {pooled:.3f}  Δ {delta:+.3f}")

    if args.emit_script:
        lines = ["#!/usr/bin/env bash",
                 "# auto-generated by kaggle/grids/auto_ladder_from_bases.py",
                 "set -uo pipefail",
                 'cd "$(dirname "${BASH_SOURCE[0]}")/../.."']
        for deck, tag, cseed, eseed, ckpt, delta, lo, pooled in sorted(eligible, key=lambda r: -r[5]):
            lines.append(
                f'bash kaggle/grids/run_single_deck_rl.sh {deck} {tag} {ckpt} {cseed} 100 {eseed}'
            )
        with open(args.emit_script, "w") as handle:
            handle.write("\n".join(lines) + "\n")
        os.chmod(args.emit_script, 0o755)
        print(f"\n[wrote] {args.emit_script}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
