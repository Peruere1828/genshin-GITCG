"""Build the per-deck specialist table from the certification reports.

The deliverable is a *set* of per-deck specialists (deck-level routing is legitimate;
matchup-level routing was shown to be noise), so the table has to be regenerated from
the raw certifications rather than hand-maintained. One row per deck:

* the certified arm with the best paired delta, provided it also reaches absolute
  parity (pooled >= expert); otherwise the best arm is shown but marked as behind;
* the gate column reports the *full* acceptance gate (pooled + strict Wilson floor +
  clean), which only becomes informative with enough seeds -- at 10 seeds the floor
  check needs a true rate of ~0.67 per matchup, so "floor=False" on small runs is a
  power statement, not a strategy statement.

Usage: python -m scripts.specialist_table [--out reports/SPECIALISTS.md]
"""

from __future__ import annotations

import argparse
import glob
import json
import os
from dataclasses import dataclass


@dataclass
class Arm:
    deck: str
    tag: str
    contestant: str
    pooled: float
    expert: float
    delta: float
    ci_low: float
    ci_high: float
    pairs: int
    bad_matchups: int
    gate_pass: bool
    floor_pass: bool
    seeds: list[int]


def collect(reports_dir: str) -> dict[str, list[Arm]]:
    arms: dict[str, list[Arm]] = {}
    for path in glob.glob(os.path.join(reports_dir, "*.json")):
        if "_2026" in os.path.basename(path):          # timestamped snapshots
            continue
        try:
            with open(path) as handle:
                data = json.load(handle)
        except Exception:
            continue
        if "paired_vs_baseline" not in data or "protocol" not in data:
            continue
        protocol, paired, summary = data["protocol"], data["paired_vs_baseline"], data["summary"]
        deck = protocol.get("contestant_deck")
        if not deck:
            continue
        gates = data.get("gates", {})
        arms.setdefault(deck, []).append(
            Arm(
                deck=deck,
                tag=data.get("tag", os.path.basename(path).replace(".json", "")),
                contestant=protocol.get("contestant", ""),
                pooled=float(summary["pooled_rate"]),
                expert=float(paired["rate_b"]),
                delta=float(paired["delta"]),
                ci_low=float(paired["ci_low"]),
                ci_high=float(paired["ci_high"]),
                pairs=int(paired.get("n_pairs") or 0),
                bad_matchups=sum(1 for v in summary["per_opponent"].values() if v["rate"] < 0.45),
                gate_pass=bool(gates.get("pass")),
                floor_pass=bool(gates.get("floor_pass")),
                seeds=list(protocol.get("seeds") or []),
            )
        )
    return arms


def pick(arms: list[Arm]) -> Arm:
    """Most defensible arm per deck.

    The same checkpoint is often certified several times (different seed sets); keep the
    largest-sample certification of each checkpoint, then prefer an arm that passed the
    full gate, then a positive delta, then the absolute pooled rate.
    """
    by_checkpoint: dict[str, Arm] = {}
    for arm in arms:
        key = arm.contestant
        current = by_checkpoint.get(key)
        if current is None or (arm.pairs, bool(arm.gate_pass)) > (current.pairs, bool(current.gate_pass)):
            by_checkpoint[key] = arm
    return max(by_checkpoint.values(), key=lambda a: (a.gate_pass, a.delta > 0, a.delta, a.pooled, a.pairs))


def render(arms: dict[str, list[Arm]]) -> str:
    rows = []
    for deck, deck_arms in arms.items():
        best = pick(deck_arms)
        rows.append(best)
    rows.sort(key=lambda a: (-a.delta, -a.pooled))
    lines = [
        "# Per-deck specialist set",
        "",
        "Auto-generated by `python -m scripts.specialist_table` from `reports/explore/*.json`.",
        "One row per deck: the best certified arm (highest paired delta, then pooled rate).",
        "",
        "| deck | pooled | expert | delta | 95% CI | pairs | matchups <45% | gate | arm |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for a in rows:
        gate = "PASS" if a.gate_pass else ("pooled+clean" if a.floor_pass else "fail")
        lines.append(
            f"| {a.deck} | {a.pooled:.4f} | {a.expert:.4f} | {a.delta:+.4f} | "
            f"[{a.ci_low:+.3f},{a.ci_high:+.3f}] | {a.pairs} | {a.bad_matchups} | {gate} | `{a.tag}` |"
        )
    passing = [a for a in rows if a.gate_pass]
    ahead = [a for a in rows if a.pooled >= a.expert]
    lines += [
        "",
        f"Decks with a certified arm: **{len(rows)}**  |  full gate PASS: **{len(passing)}**  |  "
        f"absolute parity or better vs the scripted expert: **{len(ahead)}**",
        "",
        "Note: the strict Wilson floor needs ~20 seeds per deck to be informative (at 10 seeds a "
        "true 0.50 matchup rate has a Wilson lower bound near 0.30, so the floor check fails on "
        "statistical power alone).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reports", default="reports/explore")
    parser.add_argument("--out", default="reports/SPECIALISTS.md")
    args = parser.parse_args()
    arms = collect(args.reports)
    text = render(arms)
    with open(args.out, "w") as handle:
        handle.write(text)
    print(text)
    print(f"[wrote] {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
